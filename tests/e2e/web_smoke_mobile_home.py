from playwright.sync_api import sync_playwright
import json, os
BASE=os.environ.get('SMOKE_BASE_URL', 'http://localhost:3200')
out=os.environ.get('SMOKE_SHOT_DIR', os.path.join(os.path.dirname(__file__), '..', '..', '.tmp', 'shots'))
errs=[]; results=[]
def check(n,c,extra=''):
    results.append((n,bool(c),extra)); print(('PASS' if c else 'FAIL'), n, extra[:200], flush=True)
with sync_playwright() as p:
    b=p.chromium.launch()
    ctx=b.new_context(viewport={'width':390,'height':844}, device_scale_factor=2)
    page=ctx.new_page()
    page.on('pageerror', lambda e: errs.append(str(e)))
    page.goto(BASE+'/today', wait_until='networkidle'); page.wait_for_timeout(500)
    body=page.locator('body').inner_text()
    check('today loads logged out', '今天' in body and '交给助手整理' in body)
    check('logged out notice', '未登录时' in body)
    page.screenshot(path=out+'/smoke-today-anon.png', full_page=True)
    page.goto(BASE+'/login', wait_until='networkidle')
    page.fill('#login-email','web4@example.com'); page.fill('#login-password','pa-web-verify-2026')
    page.locator('form').get_by_role('button', name='登录').click()
    page.wait_for_url('**/today', timeout=15000); page.wait_for_timeout(1200)
    check('login succeeds', '/today' in page.url)
    body=page.locator('body').inner_text()
    check('today logged in shows commute', '通勤' in body or '建议' in body, body[:300])
    page.screenshot(path=out+'/smoke-today-auth.png', full_page=True)
    page.goto(BASE+'/me/commute', wait_until='networkidle'); page.wait_for_timeout(1000)
    body=page.locator('body').inner_text()
    check('commute list has plan', '第四轮通勤验收' in body, body[:400])
    page.screenshot(path=out+'/smoke-commute-list.png', full_page=True)
    page.goto(BASE+'/me/commute/2b32ace9-2267-43ae-ac61-e221b3da5838', wait_until='networkidle'); page.wait_for_timeout(1500)
    body=page.locator('body').inner_text()
    check('commute detail renders', '计划要求' in body and '本次' in body, body[:400])
    check('old revision labelled', '旧计划版本' in body or '历史建议' in body, body[:600])
    check('unconfigured route copy', '当前无法查询新路线' in body, body[:800])
    check('no fake AI zero', 'AI 额外 0' not in body)
    page.screenshot(path=out+'/smoke-commute-detail.png', full_page=True)
    page.goto(BASE+'/matters', wait_until='networkidle'); page.wait_for_timeout(600)
    body=page.locator('body').inner_text()
    check('matters real empty state', '演示' not in body.split('事务')[-1][:60], body[:300])
    page.screenshot(path=out+'/smoke-matters.png', full_page=True)
    page.goto(BASE+'/ask', wait_until='networkidle'); page.wait_for_timeout(600)
    body=page.locator('body').inner_text()
    check('ask composer visible', '问' in body and ('发送' in body or '提问' in body), body[:300])
    page.screenshot(path=out+'/smoke-ask.png', full_page=True)
    page.goto(BASE+'/me', wait_until='networkidle'); page.wait_for_timeout(600)
    body=page.locator('body').inner_text()
    check('me shows account', 'web4@example.com' in body or '退出登录' in body, body[:400])
    page.screenshot(path=out+'/smoke-me.png', full_page=True)
    print('PAGEERRORS', json.dumps(errs, ensure_ascii=False))
    print('FAILED', [r[0] for r in results if not r[1]])
    b.close()
